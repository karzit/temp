function quoteLogText(row, i) {
  if (i === 0) return row; // 머리글
  var second = row.indexOf(",", row.indexOf(",") + 1);
  var last = row.lastIndexOf(",");
  var text = row.slice(second + 1, last);
  return row.slice(0, second + 1) + '"' + text.replace(/"/g, '""') + '"' + row.slice(last);
}

