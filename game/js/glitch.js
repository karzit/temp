  _last: null,

  // 지금 단계에서 한 줄 튀어나올지 굴린다. 안 나오면 null.
  // 같은 말이 연달아 나오지는 않게 한 번만 다시 뽑는다.
  roll: function (decay) {
    var rate = Glitch.rate(decay);
    if (!rate || Math.random() >= rate) return null;
    var text = Glitch.pick();
    if (text === Glitch._last) text = Glitch.pick();
    Glitch._last = text;
    return { who: "Aistb", text: text, tone: "bad" };
  },

  pick: function () {
    return Glitch.LINES[Math.floor(Math.random() * Glitch.LINES.length)];
  },

  // 할 말 목록 사이사이에 끼워 넣는다. 첫 줄 앞에는 넣지 않는다 —
  // 그 자리는 플레이어가 지금 무슨 상황인지 잡는 자리다.
  weave: function (list, decay) {
    if (!(Glitch.rate(decay) > 0) || !list.length) return list;
    var out = [];
    list.forEach(function (line, i) {
      out.push(line);
      if (i === list.length - 1) return; // 마지막 줄 뒤에도 넣지 않는다
      var g = Glitch.roll(decay);
      if (g) out.push(g);
    });
    return out;
  },
