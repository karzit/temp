// 웃긴 지점이다.
//
// 손으로 자리를 잡아 놓지 않는다. 고장 단계가 깊을수록 자주, 아무 데서나 튀어나온다.
// 그래야 대본이 아니라 고장으로 읽힌다. 같은 장을 두 번 해도 같은 자리에서 안 나온다.
